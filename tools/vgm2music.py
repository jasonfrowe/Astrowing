#!/usr/bin/env python3
"""Convert Furnace POKEY VGM exports to compact music data for Astro Wing.

    tools/vgm2music.py src/music/Song_01.vgm ... -o src/music/music_data.asm

Export each song from Furnace as VGM (POKEY, 60 Hz). Songs are numbered in
the order given (0, 1, 2...), and the player (mus_start in astrowing.bas)
takes that number.

Every frame's POKEY state is kept, so playback is exact at 60 Hz. Each song
has five voices: POKEY channels 1-4 and AUDCTL. A voice is a stream of:

    $00-$7F  state n: write the voice's table entry n (AUDF and AUDC; for
             the AUDCTL voice just AUDCTL). Takes one frame.
    $80-$BF  hold the current state 1-64 more frames
    $C0 lo hi len   play the len bytes at hi:lo (an earlier stretch of the
             same voice, never containing a $C0 itself), then carry on
    $FF      end of song: start the voice over

Each voice has its own table of the distinct states it uses (at most 128).
Repeated phrases become 4-byte $C0 calls, which is most of the saving.
"""

import argparse
import struct
from pathlib import Path

MINCALL = 5      # a call costs 4 bytes, so only replace 5+ bytes
MAXCALL = 255


def vgm_frames(path):
    """Full POKEY register state (AUDF1..AUDC4, AUDCTL) for every 60 Hz frame,
    from the loop point on."""
    d = Path(path).read_bytes()
    if d[:4] != b"Vgm ":
        raise SystemExit(f"{path}: not a VGM file")
    p = struct.unpack("<I", d[0x34:0x38])[0] + 0x34
    loop = struct.unpack("<I", d[0x1C:0x20])[0]
    loopoff = loop + 0x1C if loop else None
    regs = [0] * 9
    out, loopframe, acc = [], 0, 0
    while p < len(d):
        if p == loopoff:
            loopframe = len(out)
        c = d[p]
        if c == 0x66:
            break
        elif c == 0xBB:  # POKEY write
            if d[p + 1] < 9:
                regs[d[p + 1]] = d[p + 2]
            p += 3
        elif c in (0x62, 0x63):
            out.append(tuple(regs))
            p += 1
        elif c == 0x61:
            acc += struct.unpack("<H", d[p + 1:p + 3])[0]
            p += 3
        elif 0x70 <= c <= 0x7F:
            acc += (c & 15) + 1
            p += 1
        else:
            raise SystemExit(f"{path}: unsupported VGM command {c:#x}")
        while acc >= 735:
            out.append(tuple(regs))
            acc -= 735
    return out[loopframe:]


def tokens(seq, table):
    toks, prev, run = [], None, 0

    def hold(n):
        while n > 0:
            k = min(n, 64)
            toks.append(0x80 + k - 1)
            n -= k

    for st in seq:
        if st != prev:
            if prev is not None:
                hold(run)
            if st not in table:
                table.append(st)
            toks.append(table.index(st))
            prev, run = st, 0
        else:
            run += 1
    hold(run)
    if len(table) > 128:
        raise SystemExit("a voice uses more than 128 states")
    return toks


def compress(toks):
    """Greedy: each run of tokens already seen (in plain bytes) becomes a call.
    Returns a list of byte values and ('call', offset, length) entries."""
    enc, plain = [], []   # plain[k]: enc[k] is a plain token byte
    i = 0
    while i < len(toks):
        best_len, best_pos = 0, 0
        for p in range(len(enc)):
            if not plain[p] or enc[p] != toks[i]:
                continue
            n = 0
            while (i + n < len(toks) and p + n < len(enc) and plain[p + n]
                   and enc[p + n] == toks[i + n] and n < MAXCALL):
                n += 1
            if n > best_len:
                best_len, best_pos = n, p
        if best_len >= MINCALL:
            enc += [("call", best_pos, best_len), None, None, None]
            plain += [False] * 4
            i += best_len
        else:
            enc.append(toks[i])
            plain.append(True)
            i += 1
    enc.append(0xFF)
    return enc


def emit_bytes(lines, label, items):
    lines.append(label)
    row = []
    for it in items:
        if it is None:
            continue
        if isinstance(it, tuple):
            _, pos, n = it
            row += ["$C0", f"<({label}+{pos})", f">({label}+{pos})", str(n)]
        else:
            row.append(f"${it:02X}")
    for k in range(0, len(row), 12):
        lines.append("  .byte " + ",".join(row[k:k + 12]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("vgm", nargs="+")
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()

    lines = ["; Generated by tools/vgm2music.py. Do not edit.", ""]
    header = ["mus_songs"]
    total = 0
    for n, path in enumerate(a.vgm):
        fr = vgm_frames(path)
        name = f"mus_s{n}"
        sizes = []
        hdr = []
        for v in range(5):
            table = []
            seq = [(f[v * 2], f[v * 2 + 1]) for f in fr] if v < 4 else [(f[8], 0) for f in fr]
            enc = compress(tokens(seq, table))
            emit_bytes(lines, f"{name}_v{v}", enc)
            emit_bytes(lines, f"{name}_f{v}", [t[0] for t in table])
            if v < 4:
                emit_bytes(lines, f"{name}_c{v}", [t[1] for t in table])
            ctab = f"{name}_c{v}" if v < 4 else f"{name}_f{v}"
            hdr.append(f"  .byte <{name}_v{v},>{name}_v{v},<{name}_f{v},>{name}_f{v},<{ctab},>{ctab}")
            size = sum(4 if isinstance(e, tuple) else 1 for e in enc if e is not None)
            size += len(table) * (2 if v < 4 else 1)
            sizes.append(size)
        lines.append("")
        header += hdr
        total += sum(sizes) + 30
        print(f"{Path(path).name}: song {n}, {len(fr)} frames, {sum(sizes) + 30} bytes {sizes}")
    lines += header
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(f"total {total} bytes -> {a.out}")


if __name__ == "__main__":
    main()
